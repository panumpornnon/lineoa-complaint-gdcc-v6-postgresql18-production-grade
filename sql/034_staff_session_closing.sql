-- 034_staff_session_closing.sql
-- บันทึกเวลาที่เบราว์เซอร์แจ้งว่ากำลังจะปิด เพื่อปลดเซสชันให้เร็วขึ้น
--
-- ปัญหาที่แก้:
--   นโยบายหนึ่งบัญชีหนึ่งเครื่องใช้เกณฑ์ไม่มีความเคลื่อนไหวหกสิบนาทีเป็นตัวปลดเซสชัน
--   เจ้าหน้าที่ที่ปิดเครื่องที่บ้านโดยไม่กดออกจากระบบ จึงเข้าใช้งานที่ทำงานไม่ได้
--   จนกว่าจะครบหกสิบนาที ซึ่งยาวเกินไปสำหรับการทำงานจริง
--
-- วิธีแก้:
--   เมื่อเบราว์เซอร์กำลังจะปิด หน้าเว็บส่งสัญญาณมาบันทึกเวลาไว้ในคอลัมน์นี้
--   การเข้าสู่ระบบครั้งถัดไปจะถือว่าเซสชันที่ถูกทำเครื่องหมายไว้นานเกินช่วงผ่อนผัน
--   คือปิดไปแล้วจริง จึงอนุญาตให้เข้าใช้งานได้เลย ไม่ต้องรอครบหกสิบนาที
--
--   ไม่ยกเลิกเซสชันทันทีที่ได้รับสัญญาณ เพราะเหตุการณ์เดียวกันนี้เกิดตอนกดรีเฟรช
--   หน้าจอด้วย ถ้ายกเลิกทันทีการกดรีเฟรชจะกลายเป็นการออกจากระบบ
--   จึงใช้วิธีทำเครื่องหมายไว้ก่อน แล้วล้างเครื่องหมายเมื่อมีคำขอถัดไปเข้ามา
--   การรีเฟรชจะล้างเครื่องหมายเองภายในไม่กี่วินาที ส่วนการปิดจริงจะไม่มีอะไรมาล้าง
-- ---------------------------------------------------------------------------

BEGIN;

ALTER TABLE staff_sessions
  ADD COLUMN IF NOT EXISTS closing_at timestamptz;

COMMENT ON COLUMN staff_sessions.closing_at
  IS 'เวลาที่เบราว์เซอร์แจ้งว่ากำลังปิด ล้างค่าเมื่อมีคำขอถัดไปจากเซสชันเดียวกัน';

COMMIT;
